import { POLICY_FILE } from './types.ts';
import { POLICY_SCHEMA } from './validate.ts';

interface Node {
  type?: string;
  description?: string;
  enum?: unknown[];
  properties?: Record<string, Node>;
  items?: Node;
  required?: string[];
  format?: string;
}

function typeOf(node: Node): string {
  if (node.enum !== undefined) return node.enum.map((value) => `\`${JSON.stringify(value)}\``).join(', ');
  if (node.type === 'array') return node.items?.type === 'object' ? 'list of objects' : `list of ${node.items?.type ?? 'values'}s`;
  if (node.format === 'date') return 'date (YYYY-MM-DD)';
  return node.type ?? '';
}

function rows(node: Node, prefix: string, required: readonly string[] = []): string[] {
  const lines: string[] = [];
  for (const [name, child] of Object.entries(node.properties ?? {})) {
    const path = prefix === '' ? name : `${prefix}.${name}`;
    lines.push(`| \`${path}\` | ${typeOf(child)}${required.includes(name) ? ', required' : ''} | ${(child.description ?? '').replace(/\|/g, '\\|')} |`);
    if (child.type === 'object') lines.push(...rows(child, path, child.required));
    if (child.type === 'array' && child.items?.type === 'object') lines.push(...rows(child.items, `${path}[]`, child.items.required));
  }
  return lines;
}

/** docs/policy.md, generated from schema.json so that the two cannot drift apart. */
export function renderPolicy(): string {
  const schema = POLICY_SCHEMA as Node;
  return [
    '# Policy',
    '',
    '<!-- Generated by npm run docs:policy from schema.json. Do not edit by hand. -->',
    '',
    `\`${POLICY_FILE}\` at the root of a project sets what its agent components may be. \`agentcurfew init\` writes one from what the project has now: the skill sources and servers it uses, and the strict value of every setting the project already meets; a setting it does not meet yet is left loose and listed, and findings that are not about the policy, such as a secret, still fail; \`agentcurfew doctor\` checks it against [schema.json](../schema.json), and \`scan\`, \`lock\` and \`verify\` refuse to run with a policy that does not follow it.`,
    '',
    'Settings that are true or false move the level of a rule (a finding then names the setting); lists of allowed sources and servers feed the rule `out-of-policy`; `exclude` leaves paths out of everything; `exceptions` accept findings, each with a reason, and with `until` only to that date.',
    '',
    '| Field | Type | Meaning |',
    '| --- | --- | --- |',
    ...rows(schema, '', schema.required),
    '',
    'Globs: `*` stays within a path segment, `**` crosses segments, `?` is one character, and a glob that names a folder covers everything below it.',
    '',
  ].join('\n');
}
