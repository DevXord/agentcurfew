import { plannedRules, rules } from './index.ts';
import type { Rule } from './types.ts';
import { OWASP_AST } from './types.ts';

function owasp(rule: { owasp: readonly string[] }): string {
  return rule.owasp.map((id) => `${id} ${OWASP_AST[id as keyof typeof OWASP_AST]}`).join(', ');
}

/** What agentcurfew explain prints for a rule. */
export function explainText(rule: Rule): string {
  const lines = [
    `${rule.id}: ${rule.title}`,
    '',
    `Level: ${rule.level}${rule.falsePositives === undefined ? '' : ' (pattern matching: can raise false alarms)'}`,
    `OWASP Agentic Skills Top 10: ${owasp(rule)}`,
    `Checks: ${rule.kinds.join(', ')}`,
    '',
    rule.description,
    '',
    `Example: ${rule.example}`,
    '',
    `Fix: ${rule.fix}`,
  ];
  if (rule.falsePositives !== undefined) lines.push('', `False alarms: ${rule.falsePositives}`);
  return `${lines.join('\n')}\n`;
}

const md = (text: string): string => text.replace(/\|/g, '\\|');

/** docs/rules.md, generated from the rules themselves so that the two cannot drift apart. */
export function renderRules(): string {
  const lines = [
    '# Rules',
    '',
    '<!-- Generated by npm run docs:rules from src/rules/. Do not edit by hand. -->',
    '',
    'Every rule reads files only. Nothing that is found is run, and nothing is sent anywhere. `agentcurfew explain <id>` prints the same text as this page.',
    '',
    'Levels: `critical`, `high`, `medium`, `low`, `info`. `agentcurfew scan` exits with code 1 when a finding is at `--fail-on` (default `high`) or above.',
    '',
    '| Rule | Level | OWASP | Checks |',
    '| --- | --- | --- | --- |',
    ...rules.map((rule) => `| [\`${rule.id}\`](#${rule.id}) | ${rule.level} | ${rule.owasp.join(', ')} | ${rule.kinds.join(', ')} |`),
    ...plannedRules.map((rule) => `| \`${rule.id}\` (planned, phase ${rule.phase}) | | ${rule.owasp.join(', ')} | |`),
    '',
  ];
  for (const rule of rules) {
    lines.push(`## ${rule.id}`, '', `**${md(rule.title)}.** Level ${rule.level}. ${owasp(rule)}.`, '', rule.description, '', `Example: \`${rule.example.replace(/`/g, "'")}\``, '', `Fix: ${rule.fix}`, '');
    if (rule.falsePositives !== undefined) lines.push(`False alarms: ${rule.falsePositives}`, '');
  }
  lines.push(
    '## Planned',
    '',
    ...plannedRules.map((rule) => `- \`${rule.id}\`: ${rule.title} (${rule.owasp.join(', ')}). Needs phase ${rule.phase} of the plan.`),
    '',
    '## What agentcurfew does not find',
    '',
    'The rules match patterns in text. They do not judge what a text means, so they miss (OWASP AST08):',
    '',
    '- instructions that manipulate the model in plain language, with no hidden characters, links or file names to match;',
    '- harmful behaviour inside a program or package that a skill or MCP server starts, which needs the package checked (depcurfew) or the program reviewed;',
    '- what a remote MCP server or a fetched page returns at run time, since nothing is fetched;',
    '- agents, files and settings that are not in the knowledge base yet ([knowledge.md](knowledge.md)).',
    '',
    'A clean scan therefore means that none of these patterns was found, not that the configuration is safe.',
    '',
  );
  return lines.join('\n');
}
